def translate(key: str, locale: str = "zh") -> str:
    """Look up a translation key. Falls back to key itself if not found."""
    if not key:
        return key
    entry = TRANSLATIONS.get(key)
    if entry:
        return entry.get(locale, entry.get("en", key))
    return key


def _(key: str, locale: str = "zh") -> str:
    """Short alias for translate()."""
    return translate(key, locale)
